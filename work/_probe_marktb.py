import sys
import struct
sys.stdout.reconfigure(encoding='utf-8')

HEX = ("0000000000005d00000000005e00000000005f000000000060000000000061000000000062"
       "00000000005600000000005700000000005800000000005900000000005c000000000065"
       "00000000005500000000004e00000000002b00000000002c00000000005a00000000005b"
       "00000000005100000000005200000000005000000000004f000000000054000000000053"
       "000000000073000000000075000000000074000000000076000000000063000000000064"
       "00000000007d00000000007c000000000077000000000079000000000078000000000068"
       "00000000007000000000006f00000000007100000000007a0000000000d00000000000d1"
       "0000000000d20000000000d30000000000d40000000000d500000000004b00000000004a"
       "0000000000a90000000000aa0000000000ab")

b = bytes.fromhex(HEX)
print('bytes', len(b), 'entries', len(b) // 6)
base = 0x1010059C
for i in range(len(b) // 6):
    e = b[i * 6:i * 6 + 6]
    g = e[0]
    rest = struct.unpack_from('<5B', e, 1)
    print('%2d  @0x%08x  glyph=0x%02x %-4s  rest=%s' % (
        i, base + i * 6, g, repr(chr(g)) if 32 <= g < 127 else '', ' '.join('%02x' % x for x in rest)))
